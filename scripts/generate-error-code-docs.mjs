import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {ERRORS} from '../js/error-registry.mjs';

/** Compact generated index; explanations stay in the registry instead of being copied twice. */
export function generateErrorCodeDocs(){
  const lines=['# Error code reference','','Generated by `node scripts/generate-error-code-docs.mjs`. Do not edit this index by hand.','',
    'The [registry](../js/error-registry.mjs) owns fixed messages, surface-specific next steps and classification. Use `node scripts/explain-diagnostic.mjs report.txt` (or `-` for stdin) to interpret a copied v2 report offline. The tool does not fetch, check out a branch, retry writes or recover storage.','',
    '## Reading a report','',
    '- **Input:** correct the entered value; no technical panel is needed.',
    '- **State:** an expected connection or application state; details are available on demand.',
    '- **Integrity:** a stored-data or uncertain-operation check needs inspection.',
    '- **Defect:** an internal or unclassified check needs investigation.',
    '- Codes alone never grant permission to retry. All registry entries conservatively report an unknown write outcome and `retryable: false`; the application remains authoritative about what it allows.',
    '- Reports contain bounded typed facts only. Native messages, provider bodies, private identifiers and record values are excluded.',
    '- Trusted app file/line/column plus a stamped commit locate source. Function names are omitted. Unminified static modules need no source maps; if bundling/minification is ever adopted, retain source maps before relying on those frames.',
    '- The literal-code audit reports computed/forwarded calls separately. Zero unknown literal codes is not proof that every dynamic path was exercised.',
    '',`## Registered codes (${Object.keys(ERRORS).length})`,''];
  const groups=new Map;
  for(const [code,entry] of Object.entries(ERRORS)){const key=`${entry.area} / ${entry.kind}`;(groups.get(key)||groups.set(key,[]).get(key)).push(code);}
  for(const [group,codes] of [...groups].sort(([a],[b])=>a.localeCompare(b))){
    lines.push(`### ${group}`,'');
    let line='';for(const code of codes.sort()){const part='`'+code+'`';if(line.length+part.length>100){lines.push(line);line='';}line+=(line?' · ':'')+part;}if(line)lines.push(line);lines.push('');
  }
  return lines.join('\n')+'\n';
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const target=fileURLToPath(new URL('../docs/ERROR_CODES.md',import.meta.url)),expected=generateErrorCodeDocs();
  if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==expected){process.stderr.write('docs/ERROR_CODES.md is stale; run node scripts/generate-error-code-docs.mjs.\n');process.exitCode=1;}}
  else fs.writeFileSync(target,expected);
}
